package main

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func TestAddBuildTag(t *testing.T) {
	content := []byte("// Code generated by sqlc. DO NOT EDIT.\n\npackage gen\n")
	tagged := addBuildTag(content, "!pg")
	if !strings.HasPrefix(string(tagged), "//go:build !pg\n\n") {
		t.Fatalf("missing build tag prefix: %q", tagged)
	}
	if !strings.HasSuffix(string(tagged), string(content)) {
		t.Fatalf("generated content altered: %q", tagged)
	}
}

func TestRemoveStale(t *testing.T) {
	dir := t.TempDir()
	files := map[string]bool{
		"sqlite_db.go":    true,
		"sqlite_users.go": true,
		"pg_db.go":        false,
		"gen.go":          false,
	}
	for name := range files {
		if err := os.WriteFile(filepath.Join(dir, name), []byte("package gen\n"), 0o600); err != nil {
			t.Fatalf("write %s: %v", name, err)
		}
	}
	if err := removeStale(dir, "sqlite_"); err != nil {
		t.Fatalf("removeStale() error = %v", err)
	}
	for name, shouldBeGone := range files {
		_, err := os.Stat(filepath.Join(dir, name))
		if shouldBeGone && err == nil {
			t.Errorf("%s still present", name)
		}
		if !shouldBeGone && err != nil {
			t.Errorf("%s removed: %v", name, err)
		}
	}
}
